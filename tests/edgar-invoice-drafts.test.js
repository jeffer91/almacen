 assert.match(reference,/viewBox="0 0 595 842"/);
 assert.match(reference,/x="20" y="147" width="250" height="206"/);
 assert.match(reference,/x="280" y="20" width="295" height="333"/);
 assert.match(reference,/x="20" y="383" width="555" height="77"/);
 assert.match(reference,/x="20" y="493" width="40" height="25"/);
 assert.match(reference,/>1\.827<\/text>/);assert.match(reference,/>105\.05<\/text>/);
 assert.match(reference,/01 - SIN UTILIZACION DEL SISTEMA FINANCIERO/);
 const long={...l,code:"NE-12345678901234567890",quantity:1.125,unit_net:0.123456,base:0.14,tax:0.02,description:"Descripción extensa ".repeat(8),extra:"Presentación de prueba ".repeat(6)};
