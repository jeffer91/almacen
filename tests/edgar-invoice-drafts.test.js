 for(const page of pages)for(const match of page.matchAll(/<rect[^>]* y="([\d.]+)"[^>]* height="([\d.]+)"/g))assert.ok(Number(match[1])+Number(match[2])<=812);
 const js=fs.readFileSync(path.join(root,"invoices.js"),"utf8");
 assert.match(js,/window\.NICOLE_XML\.build\(d,issuer\); \/\/ validate arithmetic/);
